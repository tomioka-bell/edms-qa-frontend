const approvalSet = (
  preparer: string,
  reviewer: string,
  approver: string,
  stage: 'done' | 'review' | 'approval' | 'draft',
  dates: [string?, string?, string?] = [],
): QaDocument['approvals'] => [
  {
    role: 'Prepared by',
    name: preparer,
    position: 'Document Author',
    state: stage === 'draft' ? 'In Progress' : 'Completed',
    date: stage === 'draft' ? undefined : dates[0],
  },
  {
    role: 'Reviewed by',
    name: reviewer,
    position: 'QA Manager',
    state: stage === 'done' || stage === 'approval' ? 'Completed' : stage === 'review' ? 'In Progress' : 'Pending',
    date: stage === 'done' || stage === 'approval' ? dates[1] : undefined,
  },
  {
    role: 'Approved by',
    name: approver,
    position: 'Managing Director',
    state: stage === 'done' ? 'Completed' : stage === 'approval' ? 'In Progress' : 'Pending',
    date: stage === 'done' ? dates[2] : undefined,
  },
];

